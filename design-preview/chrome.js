document.querySelectorAll('nav.tabbar').forEach((el) => {
  const active = el.dataset.active;
  el.setAttribute('aria-label', 'Tabs');
  el.innerHTML = TABS.map(([key, label, icon, href]) =>
    `<a class="tab${key === active ? ' active' : ''}" href="${href}" aria-label="${label}">` +
    (key === 'inbox' && key !== active ? '<span class="tabbadge">3</span>' : '') +
    svg(icon, 'lg') + `<span class="sr">${label}</span></a>`
  ).join('');
});
