function svg(name, cls) {
  return `<svg class="ic ${cls || ''}" viewBox="0 0 24 24" aria-hidden="true">${ICONS[name] || ''}</svg>`;
}

document.querySelectorAll('i[data-icon]').forEach((el) => {
  el.outerHTML = svg(el.dataset.icon, el.className);
});

